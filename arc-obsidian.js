// arc-obsidian.js — optional Obsidian bridge (PERSISTENCE_PLAN.md §4): one note
// per arc in a vault folder, via the Local REST API community plugin's own
// endpoints (not its MCP layer — this is a simpler direct fetch bridge). Off by
// default; everything no-ops until a base URL + API key are saved via
// Finish the Sync - Claude Handoff.dc.html (step 06).
//
// This only works while Obsidian is open on this machine — it's a human
// surface, not a durable host. Every call is best-effort: a failure (Obsidian
// not running, wrong port, self-signed cert not yet trusted) is swallowed the
// same way arc-sync.js swallows a misconfigured Supabase project.
//
// Scope default: a single configurable vault folder (default "Arcs"), not the
// whole vault — the conservative option PERSISTENCE_PLAN.md itself named.
//
// Storage: arc-obsidian-config-v1 — { enabled, baseUrl, apiKey, folder }

const CFG_KEY = 'arc-obsidian-config-v1';
const DEFAULT_CFG = { enabled: false, baseUrl: 'https://127.0.0.1:27124', apiKey: '', folder: 'Arcs' };

export function loadConfig() {
  try { const raw = localStorage.getItem(CFG_KEY); return raw ? Object.assign({}, DEFAULT_CFG, JSON.parse(raw)) : Object.assign({}, DEFAULT_CFG); }
  catch (e) { return Object.assign({}, DEFAULT_CFG); }
}
export function saveConfig(cfg) {
  try { localStorage.setItem(CFG_KEY, JSON.stringify(cfg)); } catch (e) {}
  emit();
}
export function isConfigured(cfg) { cfg = cfg || loadConfig(); return !!(cfg.enabled && cfg.baseUrl && cfg.apiKey); }

const listeners = new Set();
export function subscribe(fn) { listeners.add(fn); return () => listeners.delete(fn); }
function emit() { listeners.forEach(fn => { try { fn(); } catch (e) {} }); }

export let lastStatus = null;

function base(cfg) { return (cfg.baseUrl || '').replace(/\/$/, ''); }
function authHeaders(cfg, contentType) { const h = { 'Authorization': 'Bearer ' + cfg.apiKey }; if (contentType) h['Content-Type'] = contentType; return h; }
function slugify(id) { return String(id).replace(/[\\/:*?"<>|]/g, '-'); }
function notePath(cfg, id) { return encodeURI(cfg.folder + '/' + slugify(id) + '.md'); }

function frontmatter(id, a) {
  return ['---', 'id: ' + id, 'series: ' + (a.series != null ? a.series : 1), 'lane: ' + (a.lane ? JSON.stringify(a.lane) : 'null'), 'accent: "' + (a.accent || '') + '"', '---', ''].join('\n');
}

// Builds the note body from the shared data model. feedsInto/fedBy live only in
// Arc Dependencies' own hardcoded ARCS array, not the canonical data — so
// wikilinks between arc notes aren't generated yet. Known gap, not silently
// faked with an empty graph.
function toMarkdown(id, a, prose) {
  let body = frontmatter(id, a) + '# ' + (a.em || id) + '\n\n';
  if (a.kicker) body += '*' + a.kicker + '*\n\n';
  if (a.sub) body += a.sub + '\n\n';
  if (prose) {
    if (prose.gain) body += '## What you gain\n' + prose.gain + '\n\n';
    if (prose.giveUp) body += '## What you give up\n' + prose.giveUp + '\n\n';
    if (prose.principle) body += '## Operating principle\n' + prose.principle + '\n\n';
    if (Array.isArray(prose.claims) && prose.claims.length) {
      body += '## Claims\n';
      prose.claims.forEach(c => { body += '- ' + (c.lead || '') + (c.body || '') + '\n'; });
      body += '\n';
    }
  }
  body += '## Months\n\n| Month | Gate |\n|---|---|\n';
  (a.quarters || []).forEach(q => (q.months || []).forEach(m => { body += '| M' + m.n + ' | ' + String(m.gate || '').replace(/\|/g, '\\|') + ' |\n'; }));
  body += '\n---\n*Generated by arc-obsidian.js — regenerating overwrites this note. Edits made in Obsidian are not read back.*\n';
  return body;
}

async function putNote(cfg, id, a, prose) {
  const res = await fetch(base(cfg) + '/vault/' + notePath(cfg, id), { method: 'PUT', headers: authHeaders(cfg, 'text/markdown'), body: toMarkdown(id, a, prose) });
  if (!res.ok) throw new Error('Obsidian PUT ' + id + ' failed: HTTP ' + res.status);
}

// Fire-and-forget, called from arc-ai.js's pushSync. Best-effort by design —
// never throws into the caller, never blocks a UI action.
export function pushOp(op, store, meta) {
  const cfg = loadConfig();
  if (!isConfigured(cfg)) return;
  if (op.op === 'delete_arc') return; // note is left in the vault as history; no delete call is made
  const id = op.id;
  if (!id || !store.data[id]) return;
  putNote(cfg, id, store.data[id], store.prose ? store.prose[id] : null)
    .then(() => { lastStatus = 'ok'; emit(); })
    .catch(e => { lastStatus = 'skipped: ' + (e && e.message || e); emit(); });
}

// Bulk (re)generation — awaited, for the handoff doc's "Generate notes now".
export async function pushAll(data, prose) {
  const cfg = loadConfig();
  if (!isConfigured(cfg)) throw new Error('Configure and save the base URL + API key first.');
  const ids = Object.keys(data || {});
  for (const id of ids) { await putNote(cfg, id, data[id], prose ? prose[id] : null); }
  return ids.length;
}

export async function testConnection(cfg) {
  const c = Object.assign({}, loadConfig(), cfg || {});
  if (!c.baseUrl || !c.apiKey) throw new Error('Base URL and API key are both required.');
  const res = await fetch(base(c) + '/', { headers: authHeaders(c) });
  if (!res.ok) throw new Error('HTTP ' + res.status + ' — check the API key and that the Local REST API plugin is running.');
  return 'Connected — Obsidian Local REST API is reachable.';
}
