function ndim(t) { if (t === "decision") return [DW, DH]; if (t === "escalation") return [EW, EH]; return [NW, NH]; }
function cpt(n, s) {
  const [w, h] = ndim(n.type);
  if (s === "top") return [n.x, n.y - h/2];
  if (s === "bottom") return [n.x, n.y + h/2];
  if (s === "left") return [n.x - w/2, n.y];
  return [n.x + w/2, n.y];
}
function epath(e, nm) {
  const fn = nm[e.from], tn = nm[e.to];
  if (!fn || !tn) return "";
  if (e.loop) {
    const [fx, fy] = cpt(fn, "left"), [tx, ty] = cpt(tn, "left");
    const lx = Math.min(fx, tx) - 88;
    return `M ${fx} ${fy} L ${lx} ${fy} L ${lx} ${ty} L ${tx} ${ty}`;
  }
  if (Math.abs(fn.y - tn.y) < 15) {
    const [fx, fy] = cpt(fn, "right"), [tx] = cpt(tn, "left");
    return `M ${fx} ${fy} L ${tx} ${fy}`;
  }
  const [fx, fy] = cpt(fn, "bottom"), [tx, ty] = cpt(tn, "top");
  const my = (fy + ty) / 2;
  return `M ${fx} ${fy} C ${fx} ${my}, ${tx} ${my}, ${tx} ${ty}`;
}
function downstream(nodeId, edges) {
  const vis = new Set(), q = [nodeId];
  while (q.length) {
    const c = q.shift();
    for (const e of edges) if (e.from === c && !vis.has(e.to)) { vis.add(e.to); q.push(e.to); }
  }
  vis.delete(nodeId);
  return [...vis];
}
