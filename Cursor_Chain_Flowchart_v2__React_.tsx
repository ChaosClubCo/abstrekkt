// ── AI CHANGE ENGINE (pure, returns {nodes, edges, errors}) ──────────────────
function applyChangeActions(change, nodes, edges) {
  if (!change?.actions || !Array.isArray(change.actions)) {
    return { nodes, edges, errors:["No actions array in change."] };
  }
  let n = { ...nodes };
  let e = [...edges];
  const errors = [];

  for (const a of change.actions) {
    try {
      switch (a.type) {
        case "add_node": {
          if (!a.id || n[a.id]) { errors.push(`add_node: invalid or duplicate id "${a.id}"`); break; }
          if (!a.removeEdge) { errors.push(`add_node: missing removeEdge field for "${a.id}"`); break; }
          const oldEdge = e.find(ed => ed.id === a.removeEdge);
          if (!oldEdge) { errors.push(`add_node: removeEdge "${a.removeEdge}" not found`); break; }
          const nodeType = a.nodeType || "process";
          const newNode = {
            id: a.id, label: a.label || a.id, type: nodeType,
            x: a.x ?? (nodes[oldEdge.from].x + nodes[oldEdge.to].x) / 2,
            y: a.y ?? (nodes[oldEdge.from].y + nodes[oldEdge.to].y) / 2,
            ph: a.ph ?? 0, em: a.em ?? 15, bp: !!a.bp,
            status:"todo", startedAt:null, completedAt:null, bypassed:false, bypassReason:"",
            checklistItems:null, w:[], u:[], c:[], i:[],
          };
          n[a.id] = newNode;
          // splice edges
          e = e.filter(ed => ed.id !== a.removeEdge);
          e.push({ id:`${a.id}_in`, from: oldEdge.from, to: a.id, label: oldEdge.label });
          e.push({ id:`${a.id}_out`, from: a.id, to: oldEdge.to });
          break;
        }
        case "update_node_label": {
          if (!n[a.id]) { errors.push(`update_node_label: node "${a.id}" not found`); break; }
          n[a.id] = { ...n[a.id], label: a.label || n[a.id].label };
          break;
        }
        case "update_node_detail": {
          if (!n[a.id]) { errors.push(`update_node_detail: node "${a.id}" not found`); break; }
          if (!["w","u","c","i"].includes(a.field)) { errors.push(`update_node_detail: invalid field "${a.field}"`); break; }
          if (!Array.isArray(a.items)) { errors.push(`update_node_detail: items must be array`); break; }
          n[a.id] = { ...n[a.id], [a.field]: a.items };
          break;
        }
        case "update_exp": {
          if (!n[a.id]) { errors.push(`update_exp: node "${a.id}" not found`); break; }
          n[a.id] = { ...n[a.id], em: typeof a.em === "number" ? a.em : n[a.id].em };
          break;
        }
        case "remove_node": {
          if (!n[a.id]) { errors.push(`remove_node: node "${a.id}" not found`); break; }
          delete n[a.id];
          // also remove orphan edges
          e = e.filter(ed => ed.from !== a.id && ed.to !== a.id);
          break;
        }
        case "add_edge": {
          if (!a.id || e.find(ed => ed.id === a.id)) { errors.push(`add_edge: invalid or duplicate id "${a.id}"`); break; }
          if (!n[a.from] || !n[a.to]) { errors.push(`add_edge: missing endpoints "${a.from}"→"${a.to}"`); break; }
          e.push({ id:a.id, from:a.from, to:a.to, label:a.label, loop:!!a.loop });
          break;
        }
        case "remove_edge": {
          const before = e.length;
          e = e.filter(ed => ed.id !== a.id);
          if (e.length === before) errors.push(`remove_edge: edge "${a.id}" not found`);
          break;
        }
        default:
          errors.push(`Unknown action type: ${a.type}`);
      }
    } catch (err) {
      errors.push(`Error in ${a.type}: ${err.message}`);
    }
  }
  return { nodes:n, edges:e, errors };
}

// ── SVG NODE (module-level render fn) ────────────────────────────────────────
function makeSvgNode(node, { selectedId, editMode, overtimeTick, inlineEditId, onMouseDown, onClick, onDblClick }) {
  if (inlineEditId === node.id) {
    // hide normal label; overlay handles rendering
    const [w, h] = ndim(node.type);
    return (
      <g key={node.id}>
        <rect x={node.x-w/2} y={node.y-h/2} width={w} height={h} rx={node.type==="terminal"?h/2:4} fill={DK.surf} stroke={C.primary} strokeWidth={2}/>
      </g>
    );
  }
  const [w, h] = ndim(node.type);
  const st = node.status || "todo";
  const sc = SC[st];
  const sel = selectedId === node.id;
  const elapsed = node.startedAt ? (Date.now() - node.startedAt) / 60000 : 0;
  const ot = node.startedAt && node.em > 0 && elapsed > node.em * 2 && overtimeTick >= 0;
  const fills = {
    todo: node.type === "escalation" ? "#1e0a00" : node.type === "terminal" ? "#12162a" : "#0c1020",
    active: node.type === "escalation" ? "#1e0a00" : "#160c38",
    done: "#071a0c",
    blocked: "#1a0707",
  };
  const fill = fills[st] || fills.todo;
  const stroke = sel ? C.primary : st === "todo" ? DK.border : sc;
  const lines = node.label.split("\n");
  let shape;
  if (node.type === "terminal") {
    shape = (
      <g>
        {ot && <rect x={node.x-w/2-8} y={node.y-h/2-8} width={w+16} height={h+16} rx={h/2+8} fill="none" stroke="#eab308" strokeWidth={1.5} strokeDasharray="5,3"/>}
        {sel && <rect x={node.x-w/2-4} y={node.y-h/2-4} width={w+8} height={h+8} rx={h/2+4} fill="none" stroke={C.primary} strokeWidth={1.5} opacity={0.5}/>}
        <rect x={node.x-w/2} y={node.y-h/2} width={w} height={h} rx={h/2} fill={fill} stroke={stroke} strokeWidth={sel?2:1.5}/>
      </g>
    );
  } else if (node.type === "decision") {
    const pts = `${node.x},${node.y-h/2} ${node.x+w/2},${node.y} ${node.x},${node.y+h/2} ${node.x-w/2},${node.y}`;
    shape = (
      <g>
        {ot && <polygon points={`${node.x},${node.y-h/2-8} ${node.x+w/2+8},${node.y} ${node.x},${node.y+h/2+8} ${node.x-w/2-8},${node.y}`} fill="none" stroke="#eab308" strokeWidth={1.5} strokeDasharray="5,3"/>}
        {sel && <polygon points={`${node.x},${node.y-h/2-4} ${node.x+w/2+4},${node.y} ${node.x},${node.y+h/2+4} ${node.x-w/2-4},${node.y}`} fill="none" stroke={C.primary} strokeWidth={1.5} opacity={0.5}/>}
        <polygon points={pts} fill={fill} stroke={sel?C.primary:C.accent} strokeWidth={sel?2:1.5}/>
      </g>
    );
  } else if (node.type === "escalation") {
    shape = (
      <g>
        {ot && <rect x={node.x-w/2-8} y={node.y-h/2-8} width={w+16} height={h+16} rx={6} fill="none" stroke="#eab308" strokeWidth={1.5} strokeDasharray="5,3"/>}
        {sel && <rect x={node.x-w/2-4} y={node.y-h/2-4} width={w+8} height={h+8} rx={6} fill="none" stroke={C.primary} strokeWidth={1.5} opacity={0.5}/>}
        <rect x={node.x-w/2} y={node.y-h/2} width={w} height={h} rx={4} fill={fill} stroke={C.accent} strokeWidth={sel?2:1.5}/>
      </g>
    );
  } else {
    shape = (
      <g>
        {ot && <rect x={node.x-w/2-8} y={node.y-h/2-8} width={w+16} height={h+16} rx={7} fill="none" stroke="#eab308" strokeWidth={1.5} strokeDasharray="5,3"/>}
        {sel && <rect x={node.x-w/2-4} y={node.y-h/2-4} width={w+8} height={h+8} rx={7} fill="none" stroke={C.primary} strokeWidth={1.5} opacity={0.5}/>}
        <rect x={node.x-w/2} y={node.y-h/2} width={w} height={h} rx={4} fill={fill} stroke={stroke} strokeWidth={sel?2:1.5}/>
        {node.bp && <rect x={node.x-w/2} y={node.y-h/2} width={3} height={h} rx={1.5} fill="#0891b2"/>}
        {node.isCL && <rect x={node.x-w/2} y={node.y-h/2} width={3} height={h} rx={1.5} fill={C.primary}/>}
      </g>
    );
  }
  return (
    <g key={node.id}
      style={{ cursor: editMode ? "grab" : "pointer" }}
      onMouseDown={e => { e.stopPropagation(); onMouseDown(e, node); }}
      onClick={e => { e.stopPropagation(); onClick(node); }}
      onDoubleClick={e => { e.stopPropagation(); onDblClick(node); }}>
      {shape}
      {lines.map((l, i) => (
        <text key={i} x={node.x} y={node.y + (i - (lines.length-1)/2) * 14}
          textAnchor="middle" dominantBaseline="central"
          fill="#dde4f0" fontSize={11} fontFamily="system-ui" fontWeight={500}
          style={{ pointerEvents:"none", userSelect:"none" }}>
          {l}
        </text>
      ))}
      {st !== "todo" && <circle cx={node.x+w/2-7} cy={node.y-h/2+7} r={4} fill={sc} stroke={DK.bg} strokeWidth={1.5}/>}
      {node.bypassed && <text x={node.x} y={node.y+h/2+12} textAnchor="middle" fill="#0891b2" fontSize={9} fontFamily="system-ui">BYPASSED</text>}
      {node.type === "escalation" && st !== "done" && <text x={node.x} y={node.y+h/2+12} textAnchor="middle" fill={C.accent} fontSize={9} fontFamily="system-ui">↩ Resolve to return to 7A</text>}
      {node.bp && st === "todo" && !node.bypassed && <text x={node.x-w/2+8} y={node.y+h/2-5} fill="#0891b2" fontSize={9} fontFamily="system-ui">⤵ skippable</text>}
    </g>
  );
}

// ── ERROR BOUNDARY ───────────────────────────────────────────────────────────
class ErrorBoundary extends Component {
  constructor(p) { super(p); this.state = { err:null }; }
  static getDerivedStateFromError(e) { return { err:e }; }
  componentDidCatch(e, i) { console.error("FlowchartError:", e, i); }
  render() {
    if (this.state.err) return (
      <div style={{ padding:24, color:C.blocked, fontFamily:"system-ui" }}>
        <strong style={{ fontSize:14 }}>Something went wrong.</strong>
        <pre style={{ marginTop:10, fontSize:11, color:"#94a3b8", background:DK.surf, padding:10, borderRadius:4, whiteSpace:"pre-wrap", border:`1px solid ${DK.border}` }}>{this.state.err.message}</pre>
        <button onClick={() => this.setState({ err:null })} style={{ marginTop:12, padding:"6px 14px", background:C.primary, color:"#fff", border:"none", borderRadius:4, cursor:"pointer", fontSize:12, fontWeight:700 }}>Try again</button>
      </div>
    );
    return this.props.children;
  }
}

// ── SESSION TIMER ────────────────────────────────────────────────────────────
function SessionTimer({ startedAt }) {
  const [el, setEl] = useState(0);
  useEffect(() => {
    if (!startedAt) return;
    const id = setInterval(() => setEl(Date.now() - startedAt), 1000);
    return () => clearInterval(id);
  }, [startedAt]);
  if (!startedAt) return <span style={{ color:DK.sub, fontSize:11 }}>Not started</span>;
  return <span style={{ color:"#93c5fd", fontSize:11 }}>⏱ {fmt(el)}</span>;
}

// ── AI PANEL ─────────────────────────────────────────────────────────────────
function AIPanel({ selectedNode, conversation, setConversation, addLog, applyAIChange }) {
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const [editM, setEditM] = useState(false);
  const [pending, setPending] = useState(null);
  const scrollRef = useRef(null);
  const abortRef = useRef(null);

  useEffect(() => {
    if (scrollRef.current) scrollRef.current.scrollTop = scrollRef.current.scrollHeight;
  }, [conversation]);

  useEffect(() => () => { if (abortRef.current) abortRef.current.abort(); }, []);

  const send = useCallback(async (txt) => {
    if (!txt || loading) return;
    const nodeCtx = selectedNode ? `\n\nACTIVE NODE: ${selectedNode.label.replace("\n"," ")} (${selectedNode.status})\nPhase: ${PHASE_NAMES[selectedNode.ph||0] || "N/A"}` : "";
    const editCtx = editM ? "\n\nEDIT MODE ACTIVE — output [FLOWCHART_CHANGE] block if structural change is suggested." : "";
    const userMsg = { role:"user", content: txt + nodeCtx + editCtx, displayContent: txt };
    setConversation(prev => [...prev, userMsg]);
    setLoading(true);
    abortRef.current = new AbortController();
    try {
      const apiMessages = [...conversation, userMsg].filter(m => !m.error).map(({ role, content }) => ({ role, content }));
      const r = await fetch("https://api.anthropic.com/v1/messages", {
        method:"POST",
        headers:{ "Content-Type":"application/json" },
        signal: abortRef.current.signal,
        body: JSON.stringify({ model:"claude-sonnet-4-20250514", max_tokens:800, system:AI_SYS, messages:apiMessages }),
      });
      if (!r.ok) {
        const eb = await r.json().catch(() => ({}));
        throw new Error(eb.error?.message || `HTTP ${r.status}`);
      }
      const d = await r.json();
      const text = d.content?.find(b => b.type === "text")?.text || "No response received.";
      setConversation(prev => [...prev, { role:"assistant", content:text }]);
      if (editM) { const ch = parseChange(text); if (ch) setPending(ch); }
      addLog(`AI: ${txt.slice(0, 40)}`);
    } catch (e) {
      if (e.name === "AbortError") return;
      setConversation(prev => [...prev, { role:"assistant", content:`⚠ ${e.message}`, error:true }]);
    } finally {
      setLoading(false);
    }
  }, [selectedNode, editM, addLog, loading, conversation, setConversation]);

  const handleSend = useCallback(() => {
    const t = input.trim();
    if (!t) return;
    setInput("");
    send(t);
  }, [input, send]);

  const applyPending = useCallback(() => {
    if (!pending) return;
    const result = applyAIChange(pending);
    if (result.errors.length) {
      setConversation(prev => [...prev, { role:"assistant", content:`⚠ Apply errors:\n${result.errors.join("\n")}`, error:true }]);
    } else {
      addLog(`AI edit applied: ${pending.actions.length} action(s)`);
    }
    setPending(null);
  }, [pending, applyAIChange, addLog, setConversation]);

  const bubble = (role, error) => ({
    padding:"8px 11px",
    borderRadius: role === "user" ? "10px 10px 2px 10px" : "10px 10px 10px 2px",
    background: role === "user" ? C.primary : error ? "#2d0808" : DK.surf,
    border: `1px solid ${role === "user" ? C.primary : DK.border}`,
    color: error ? C.blocked : "#dde4f0",
    fontSize:12, lineHeight:1.5,
    maxWidth:"90%",
    alignSelf: role === "user" ? "flex-end" : "flex-start",
    whiteSpace:"pre-wrap", wordBreak:"break-word",
  });

  const actionLabel = (a) => {
    switch (a.type) {
      case "add_node": return `+ Add node "${a.label || a.id}" (splice on ${a.removeEdge})`;
      case "update_node_label": return `~ Rename ${a.id} → "${a.label}"`;
      case "update_node_detail": return `~ Update ${a.id} ${a.field} (${a.items?.length || 0} items)`;
      case "update_exp": return `~ ${a.id} expected = ${a.em}min`;
      case "remove_node": return `− Remove node ${a.id}`;
      case "add_edge": return `+ Edge ${a.from} → ${a.to}`;
      case "remove_edge": return `− Edge ${a.id}`;
      default: return JSON.stringify(a).slice(0, 60);
    }
  };

  return (
    <div style={{ display:"flex", flexDirection:"column", height:"100%", overflow:"hidden" }}>
      <div style={{ display:"flex", alignItems:"center", justifyContent:"space-between", marginBottom:8, flexShrink:0 }}>
        <span style={{ fontSize:10, color:DK.sub, overflow:"hidden", textOverflow:"ellipsis", whiteSpace:"nowrap", flex:1 }}>
          {selectedNode ? `Node: ${selectedNode.label.replace("\n"," ")}` : "No node selected"}
        </span>
        <button onClick={() => setEditM(e => !e)}
          style={{ fontSize:10, padding:"2px 8px", borderRadius:3, border:"none", cursor:"pointer", fontWeight:700,
            background: editM ? C.primary : DK.surf, color: editM ? "#fff" : DK.sub, marginLeft:6, flexShrink:0 }}>
          {editM ? "✎ EDIT ON" : "✎ Edit"}
        </button>
      </div>
      {pending && (
        <div style={{ background:"#071a0c", border:`1px solid ${C.done}`, borderRadius:4, padding:8, marginBottom:8, flexShrink:0 }}>
          <div style={{ fontSize:11, color:"#4ade80", fontWeight:700, marginBottom:6 }}>📝 Proposed Change ({pending.actions?.length || 0} action{pending.actions?.length === 1 ? "" : "s"})</div>
          {pending.summary && <div style={{ fontSize:11, color:"#dde4f0", marginBottom:6, lineHeight:1.4 }}>{pending.summary}</div>}
          <div style={{ background:DK.bg, padding:"5px 7px", borderRadius:3, marginBottom:7, maxHeight:120, overflowY:"auto" }}>
            {pending.actions?.map((a, i) => (
              <div key={i} style={{ fontSize:10, color:"#9ca3af", fontFamily:"ui-monospace,monospace", lineHeight:1.5 }}>
                {actionLabel(a)}
              </div>
            ))}
          </div>
          <div style={{ display:"flex", gap:6 }}>
            <button onClick={applyPending}
              style={{ flex:1, padding:"4px 0", background:C.done, color:"#fff", border:"none", borderRadius:3, cursor:"pointer", fontSize:11, fontWeight:700 }}>Apply</button>
            <button onClick={() => setPending(null)}
              style={{ flex:1, padding:"4px 0", background:DK.surf, color:DK.sub, border:`1px solid ${DK.border}`, borderRadius:3, cursor:"pointer", fontSize:11 }}>Dismiss</button>
          </div>
        </div>
      )}
      <div ref={scrollRef} style={{ flex:1, overflowY:"auto", display:"flex", flexDirection:"column", gap:8, marginBottom:8, paddingRight:2 }}>
        {conversation.length === 0 && (
          <div style={{ color:DK.sub, fontSize:12, textAlign:"center", marginTop:20 }}>
            Ask anything about the current phase.<br/>Select a node first for targeted help.
          </div>
        )}
        {conversation.map((m, i) => <div key={i} style={bubble(m.role, m.error)}>{m.displayContent || m.content}</div>)}
        {loading && <div style={{ color:DK.sub, fontSize:12, fontStyle:"italic" }}>Thinking…</div>}
      </div>
      <div style={{ display:"flex", gap:6, flexShrink:0 }}>
        <input value={input} onChange={e => setInput(e.target.value)}
          onKeyDown={e => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); handleSend(); } }}
          placeholder="Ask AI…"
          style={{ flex:1, padding:"7px 10px", background:DK.surf, border:`1px solid ${DK.border}`, borderRadius:4, color:"#dde4f0", fontSize:12, outline:"none" }}/>
        <button onClick={handleSend} disabled={loading || !input.trim()}
          style={{ padding:"0 14px", background:C.primary, color:"#fff", border:"none", borderRadius:4, cursor: loading ? "not-allowed" : "pointer", fontSize:14, opacity: loading || !input.trim() ? 0.5 : 1 }}>↑</button>
      </div>
    </div>
  );
}

