// ── INLINE EDIT OVERLAY ──────────────────────────────────────────────────────
function InlineEditOverlay({ node, value, onChange, onCommit, onCancel, pan, zoom }) {
  const inputRef = useRef(null);
  useEffect(() => { if (inputRef.current) { inputRef.current.focus(); inputRef.current.select(); } }, []);
  if (!node) return null;
  const [w, h] = ndim(node.type);
  const sx = node.x * zoom + pan.x - (w * zoom) / 2;
  const sy = node.y * zoom + pan.y - (h * zoom) / 2;
  return (
    <div style={{ position:"absolute", left:sx, top:sy, width:w*zoom, height:h*zoom, zIndex:50 }}>
      <textarea ref={inputRef} value={value} onChange={e => onChange(e.target.value)}
        onBlur={onCommit}
        onKeyDown={e => {
          if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); onCommit(); }
          else if (e.key === "Escape") { e.preventDefault(); onCancel(); }
        }}
        style={{
          width:"100%", height:"100%", padding:4,
          background: DK.surf, color:"#dde4f0",
          border:`2px solid ${C.primary}`,
          borderRadius: node.type === "terminal" ? (h*zoom)/2 : 4,
          fontSize: Math.max(9, 11*zoom), fontFamily:"system-ui", fontWeight:500,
          textAlign:"center", resize:"none", outline:"none", boxSizing:"border-box",
        }}/>
    </div>
  );
}

