// ── MAIN APP ─────────────────────────────────────────────────────────────────
export default function CursorChainFlowchart() {
  const [nodes, setNodes] = useState(INIT_NODES);
  const [edges, setEdges] = useState(INIT_EDGES);
  const [selectedId, setSelectedId] = useState(null);
  const [tab, setTab] = useState("details");
  const [editMode, setEditMode] = useState(false);
  const [sessionStart, setSessionStart] = useState(null);
  const [sessionLog, setSessionLog] = useState([]);
  const [nodeNotes, setNodeNotes] = useState({});
  const [aiConversation, setAiConversation] = useState([]);
  const [bypassModal, setBypassModal] = useState(null);
  const [bypassReason, setBypassReason] = useState("");
  const [downstreamModal, setDownstreamModal] = useState(null);
  const [saveLabel, setSaveLabel] = useState("💾 Save");
  const [autoSaveLabel, setAutoSaveLabel] = useState("");
  const [initialized, setInitialized] = useState(false);
  const [overtimeTick, setOvertimeTick] = useState(0);
  const [inlineEditId, setInlineEditId] = useState(null);
  const [inlineEditValue, setInlineEditValue] = useState("");

  const svgGRef = useRef(null);
  const fileInputRef = useRef(null);
  const panRef = useRef({ x:40, y:20 });
  const zoomRef = useRef(0.52);
  const panStartRef = useRef(null);
  const nodeDragRef = useRef(null);
  const editRef = useRef(editMode);
  const dirtyRef = useRef(false);
  useEffect(() => { editRef.current = editMode; }, [editMode]);

  // Overtime tick
  useEffect(() => {
    const id = setInterval(() => setOvertimeTick(t => t + 1), 60_000);
    return () => clearInterval(id);
  }, []);

  // Initial load
  useEffect(() => {
    (async () => {
      try {
        const r = await window.storage.get(SK);
        if (r?.value) {
          const s = JSON.parse(r.value);
          if (s.nodes) setNodes(s.nodes);
          if (s.edges) setEdges(s.edges);
          if (s.log) setSessionLog(s.log);
          if (s.notes) setNodeNotes(s.notes);
          if (s.sessionStart) setSessionStart(s.sessionStart);
          if (s.aiConversation) setAiConversation(s.aiConversation);
        }
      } catch { /* no saved data */ } finally { setInitialized(true); }
    })();
  }, []);

  const applyT = useCallback(() => {
    if (svgGRef.current) svgGRef.current.setAttribute("transform", `translate(${panRef.current.x},${panRef.current.y}) scale(${zoomRef.current})`);
  }, []);
  useEffect(() => { applyT(); });

  // Imperative save (returns promise)
  const saveNow = useCallback(async (snapshot) => {
    try {
      await window.storage.set(SK, JSON.stringify(snapshot));
      return { ok:true };
    } catch (err) {
      return { ok:false, error: err.message };
    }
  }, []);

  const doSave = useCallback(() => {
    saveNow({ nodes, edges, log:sessionLog, notes:nodeNotes, sessionStart, aiConversation }).then(r => {
      if (r.ok) { setSaveLabel("✓ Saved"); setTimeout(() => setSaveLabel("💾 Save"), 2000); dirtyRef.current = false; }
      else setSaveLabel("⚠ Failed");
    });
  }, [nodes, edges, sessionLog, nodeNotes, sessionStart, aiConversation, saveNow]);

  // Auto-save (debounced) — only after init, only when dirty
  useEffect(() => {
    if (!initialized) return;
    dirtyRef.current = true;
    const t = setTimeout(() => {
      if (!dirtyRef.current) return;
      saveNow({ nodes, edges, log:sessionLog, notes:nodeNotes, sessionStart, aiConversation }).then(r => {
        if (r.ok) { setAutoSaveLabel("⟳ auto-saved"); dirtyRef.current = false; setTimeout(() => setAutoSaveLabel(""), 1500); }
        else setAutoSaveLabel("⚠ auto-save failed");
      });
    }, AUTOSAVE_MS);
    return () => clearTimeout(t);
  }, [nodes, edges, sessionLog, nodeNotes, sessionStart, aiConversation, initialized, saveNow]);

  const addLog = useCallback((text) => { setSessionLog(p => [...p, { ts:Date.now(), text }]); }, []);

  const setNodeStatus = useCallback((id, st, force = false) => {
    setNodes(prev => {
      if (!force && (st === "done" || st === "active")) {
        const ds = downstream(id, edges);
        const aff = ds.filter(nid => prev[nid] && (prev[nid].status === "active" || prev[nid].status === "done"));
        if (aff.length > 0) {
          setDownstreamModal({ nodeId:id, newStatus:st, affected:aff, nodeLabel:prev[id].label });
          return prev;
        }
      }
      const n = { ...prev };
      const nd = { ...n[id] };
      nd.status = st;
      if (st === "active") nd.startedAt = Date.now();
      if (st === "done") nd.completedAt = Date.now();
      if (st === "todo") { nd.startedAt = null; nd.completedAt = null; }
      if (st === "done" && nd.retTo) {
        const rn = { ...n[nd.retTo] };
        rn.status = "active";
        rn.startedAt = Date.now();
        n[nd.retTo] = rn;
      }
      n[id] = nd;
      return n;
    });
    addLog(`${nodes[id]?.label?.replace("\n"," ") || id} → ${st}`);
  }, [edges, addLog, nodes]);

  const setCheckItem = useCallback((nodeId, itemId, status) => {
    setNodes(prev => {
      const n = { ...prev };
      const nd = { ...n[nodeId] };
      nd.checklistItems = nd.checklistItems.map(i => i.id === itemId ? { ...i, status } : i);
      n[nodeId] = nd;
      return n;
    });
  }, []);

  const confirmBypass = useCallback(() => {
    if (!bypassModal) return;
    setNodes(p => ({
      ...p,
      [bypassModal.nodeId]: { ...p[bypassModal.nodeId], status:"done", bypassed:true, bypassReason, completedAt:Date.now() }
    }));
    addLog(`Bypassed: ${nodes[bypassModal.nodeId]?.label?.replace("\n"," ")} — ${bypassReason || "(no reason)"}`);
    setBypassModal(null);
    setBypassReason("");
  }, [bypassModal, bypassReason, nodes, addLog]);

  // AI change application
  const applyAIChange = useCallback((change) => {
    const result = applyChangeActions(change, nodes, edges);
    if (result.errors.length === 0 || (result.errors.length < change.actions.length)) {
      setNodes(result.nodes);
      setEdges(result.edges);
    }
    return result;
  }, [nodes, edges]);

  // Inline edit handlers
  const startInlineEdit = useCallback((node) => {
    if (!editRef.current) return;
    setInlineEditId(node.id);
    setInlineEditValue(node.label);
  }, []);

  const commitInlineEdit = useCallback(() => {
    if (!inlineEditId) return;
    const newLabel = inlineEditValue.trim();
    if (newLabel) {
      setNodes(prev => ({ ...prev, [inlineEditId]: { ...prev[inlineEditId], label: newLabel } }));
      addLog(`Renamed ${inlineEditId} → "${newLabel.replace("\n"," ")}"`);
    }
    setInlineEditId(null);
    setInlineEditValue("");
  }, [inlineEditId, inlineEditValue, addLog]);

  const cancelInlineEdit = useCallback(() => {
    setInlineEditId(null);
    setInlineEditValue("");
  }, []);

  // Mouse handlers
  const onNodeMouseDown = useCallback((e, node) => {
    if (!editRef.current) return;
    if (inlineEditId) return;
    nodeDragRef.current = { nodeId:node.id, sx:e.clientX, sy:e.clientY, ox:node.x, oy:node.y };
  }, [inlineEditId]);

  const onNodeClick = useCallback((node) => { setSelectedId(node.id); setTab("details"); }, []);

  const onCanvasDown = useCallback((e) => {
    if (nodeDragRef.current) return;
    panStartRef.current = { x:e.clientX - panRef.current.x, y:e.clientY - panRef.current.y };
  }, []);

  const onMouseMove = useCallback((e) => {
    if (nodeDragRef.current) {
      const { nodeId, sx, sy, ox, oy } = nodeDragRef.current;
      const dx = (e.clientX - sx) / zoomRef.current;
      const dy = (e.clientY - sy) / zoomRef.current;
      setNodes(p => ({ ...p, [nodeId]: { ...p[nodeId], x:ox+dx, y:oy+dy } }));
      return;
    }
    if (panStartRef.current) {
      panRef.current = { x:e.clientX - panStartRef.current.x, y:e.clientY - panStartRef.current.y };
      applyT();
    }
  }, [applyT]);

  const onMouseUp = useCallback(() => { nodeDragRef.current = null; panStartRef.current = null; }, []);

  const onWheel = useCallback((e) => {
    e.preventDefault();
    zoomRef.current = Math.max(0.18, Math.min(3, zoomRef.current * (e.deltaY < 0 ? 1.12 : 0.88)));
    applyT();
  }, [applyT]);

  const resetView = useCallback(() => { panRef.current = { x:40, y:20 }; zoomRef.current = 0.52; applyT(); }, [applyT]);

  const copyTicket = useCallback(() => {
    const lines = Object.values(nodes)
      .filter(n => n.status === "done" && n.completedAt)
      .sort((a, b) => a.completedAt - b.completedAt)
      .map(n => `[${fmtTs(n.completedAt)}] ✓ ${n.label.replace("\n"," ")}${n.bypassed ? " (BYPASSED)" : ""}`)
      .join("\n");
    navigator.clipboard.writeText(`CURSOR CHAIN SESSION\n${"=".repeat(40)}\n${lines || "(no completed steps)"}\n`);
    addLog("Ticket copied");
  }, [nodes, addLog]);

  // Export full session as JSON download
  const exportJSON = useCallback(() => {
    const snapshot = { version:"v2", exportedAt:Date.now(), nodes, edges, log:sessionLog, notes:nodeNotes, sessionStart, aiConversation };
    const blob = new Blob([JSON.stringify(snapshot, null, 2)], { type:"application/json" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `cursor-chain-${new Date().toISOString().slice(0,10)}.json`;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => { document.body.removeChild(a); URL.revokeObjectURL(url); }, 100);
    addLog("Session exported as JSON");
  }, [nodes, edges, sessionLog, nodeNotes, sessionStart, aiConversation, addLog]);

  const importJSON = useCallback((file) => {
    if (!file) return;
    const reader = new FileReader();
    reader.onload = (e) => {
      try {
        const s = JSON.parse(e.target.result);
        if (s.nodes) setNodes(s.nodes);
        if (s.edges) setEdges(s.edges);
        if (s.log) setSessionLog(s.log);
        if (s.notes) setNodeNotes(s.notes);
        if (s.sessionStart) setSessionStart(s.sessionStart);
        if (s.aiConversation) setAiConversation(s.aiConversation);
        addLog(`Imported session from ${file.name}`);
      } catch (err) {
        alert(`Import failed: ${err.message}`);
      }
    };
    reader.readAsText(file);
  }, [addLog]);

  // Keyboard shortcuts
  useEffect(() => {
    const handler = (e) => {
      // Esc closes modals + cancels inline edit
      if (e.key === "Escape") {
        if (inlineEditId) { cancelInlineEdit(); return; }
        if (bypassModal) { setBypassModal(null); setBypassReason(""); return; }
        if (downstreamModal) { setDownstreamModal(null); return; }
      }
      // Cmd/Ctrl+S → save
      if ((e.metaKey || e.ctrlKey) && e.key === "s") {
        e.preventDefault();
        doSave();
      }
      // Cmd/Ctrl+P → print
      if ((e.metaKey || e.ctrlKey) && e.key === "p") {
        e.preventDefault();
        window.print();
      }
    };
    window.addEventListener("keydown", handler);
    return () => window.removeEventListener("keydown", handler);
  }, [bypassModal, downstreamModal, inlineEditId, cancelInlineEdit, doSave]);

  const selectedNode = selectedId ? nodes[selectedId] : null;
  const pg = phaseGroups(nodes);
  const svgCtx = { selectedId, editMode, overtimeTick, inlineEditId, onMouseDown:onNodeMouseDown, onClick:onNodeClick, onDblClick:startInlineEdit };

  if (!initialized) return (
    <div style={{ width:"100vw", height:"100vh", display:"flex", alignItems:"center", justifyContent:"center", background:DK.bg, color:DK.sub, fontSize:13, fontFamily:"system-ui" }}>
      Loading…
    </div>
  );

  const Btn = (label, onClick, active, title) => (
    <button onClick={onClick} title={title}
      style={{ padding:"4px 10px", background: active ? C.primary : DK.surf, color: active ? "#fff" : DK.sub, border:`1px solid ${DK.border}`, borderRadius:4, cursor:"pointer", fontSize:10, fontWeight:700 }}>
      {label}
    </button>
  );

  return (
    <ErrorBoundary>
      <style>{PRINT_CSS}</style>
      <input ref={fileInputRef} type="file" accept=".json" style={{ display:"none" }}
        onChange={e => { const f = e.target.files?.[0]; if (f) importJSON(f); e.target.value = ""; }}/>
      <div className="ccf-app" style={{ width:"100vw", height:"100vh", display:"flex", flexDirection:"column", background:DK.bg, overflow:"hidden", fontFamily:"system-ui" }}>
        {/* TOP BAR */}
        <div className="ccf-no-print" style={{ height:44, background:DK.surf, borderBottom:`1px solid ${DK.border}`, display:"flex", alignItems:"center", padding:"0 12px", gap:8, flexShrink:0 }}>
          <div style={{ width:7, height:7, borderRadius:"50%", background:C.primary }}/>
          <span style={{ fontSize:12, fontWeight:800, color:"#dde4f0", letterSpacing:"0.3px", marginRight:6 }}>Cursor AI Prompt Chain</span>
          <span style={{ fontSize:9, color:DK.sub, background:DK.bg, padding:"1px 7px", borderRadius:10, border:`1px solid ${DK.border}` }}>8 Phases · {Object.keys(nodes).length} Steps</span>
          <div style={{ flex:1 }}/>
          {autoSaveLabel && <span style={{ fontSize:10, color:DK.sub, fontStyle:"italic", marginRight:4 }}>{autoSaveLabel}</span>}
          {!sessionStart
            ? <button onClick={() => { setSessionStart(Date.now()); addLog("Session started"); }} style={{ padding:"4px 12px", background:C.primary, color:"#fff", border:"none", borderRadius:4, cursor:"pointer", fontSize:10, fontWeight:800 }}>▶ Start</button>
            : <SessionTimer startedAt={sessionStart}/>
          }
          {Btn(editMode ? "⊹ Arrange" : "⊹ Edit", () => setEditMode(e => !e), editMode, "Toggle arrange mode (drag + double-click to rename)")}
          {Btn(saveLabel, doSave, false, "Save (Cmd/Ctrl+S)")}
          {Btn("📋 Copy", copyTicket, false, "Copy completed steps as ticket text")}
          {Btn("📤 Export", exportJSON, false, "Download session as JSON")}
          {Btn("📥 Import", () => fileInputRef.current?.click(), false, "Load session from JSON")}
          {Btn("🖨", () => window.print(), false, "Print (Cmd/Ctrl+P)")}
          {Btn("⟲", resetView, false, "Reset zoom + pan")}
        </div>

        {/* MAIN */}
        <div style={{ flex:1, display:"flex", overflow:"hidden" }}>
          {/* CANVAS */}
          <div className="ccf-canvas" style={{ flex:1, position:"relative", overflow:"hidden", cursor:"grab" }}
            onMouseDown={onCanvasDown} onMouseMove={onMouseMove} onMouseUp={onMouseUp} onMouseLeave={onMouseUp} onWheel={onWheel}>
            <svg width="100%" height="100%" style={{ background:DK.bg }}>
              <defs>
                <marker id="arr" markerWidth={8} markerHeight={7} refX={7} refY={3.5} orient="auto">
                  <path d="M0,0 L0,7 L8,3.5 z" fill="#2a3550"/>
                </marker>
                <marker id="arr-acc" markerWidth={8} markerHeight={7} refX={7} refY={3.5} orient="auto">
                  <path d="M0,0 L0,7 L8,3.5 z" fill={C.accent}/>
                </marker>
              </defs>
              <g ref={svgGRef}>
                {Object.entries(pg).map(([ph, { min, max }]) => (
                  <g key={ph}>
                    <rect x={215} y={min} width={490} height={max-min} rx={5} fill={PHASE_FG[ph]}/>
                    <text x={222} y={min+13} fontSize={9} fill={C.primary} fontFamily="system-ui" fontWeight={700} opacity={0.65}>{PHASE_NAMES[ph]}</text>
                  </g>
                ))}
                {edges.map(e => {
                  const fn = nodes[e.from], tn = nodes[e.to];
                  if (!fn || !tn) return null;
                  const path = epath(e, nodes);
                  const isL = !!e.loop;
                  const [fx, fy] = cpt(fn, "bottom");
                  const [tx, ty] = cpt(tn, "top");
                  const lx = (fx + tx) / 2, ly = (fy + ty) / 2;
                  return (
                    <g key={e.id}>
                      <path d={path} fill="none" stroke={isL ? C.accent : "#1e2840"} strokeWidth={isL ? 1.8 : 1.5} strokeDasharray={isL ? "5,3" : ""} markerEnd={isL ? "url(#arr-acc)" : "url(#arr)"}/>
                      {e.label && (
                        <>
                          <rect x={lx-20} y={ly-8} width={40} height={15} rx={3} fill={DK.surf} opacity={0.92}/>
                          <text x={lx} y={ly+1} textAnchor="middle" dominantBaseline="middle" fontSize={9} fontFamily="system-ui" fontWeight={700} fill={isL ? C.accent : "#64748b"}>{e.label}</text>
                        </>
                      )}
                    </g>
                  );
                })}
                {Object.values(nodes).map(n => makeSvgNode(n, svgCtx))}
              </g>
            </svg>

            {/* Inline edit overlay (positioned in screen space, follows pan/zoom) */}
            {inlineEditId && (
              <InlineEditOverlay
                node={nodes[inlineEditId]}
                value={inlineEditValue}
                onChange={setInlineEditValue}
                onCommit={commitInlineEdit}
                onCancel={cancelInlineEdit}
                pan={panRef.current}
                zoom={zoomRef.current}
              />
            )}

            <div className="ccf-no-print" style={{ position:"absolute", bottom:12, left:12, display:"flex", flexDirection:"column", gap:3 }}>
              {[["+", () => { zoomRef.current = Math.min(3, zoomRef.current * 1.2); applyT(); }],
                ["−", () => { zoomRef.current = Math.max(0.18, zoomRef.current * 0.82); applyT(); }],
                ["⟲", resetView]].map(([l, fn]) => (
                <button key={l} onClick={fn}
                  style={{ width:28, height:28, background:DK.surf, border:`1px solid ${DK.border}`, borderRadius:4, cursor:"pointer", fontSize:13, display:"flex", alignItems:"center", justifyContent:"center", color:DK.sub }}>
                  {l}
                </button>
              ))}
            </div>
            {editMode && (
              <div className="ccf-no-print" style={{ position:"absolute", top:10, left:"50%", transform:"translateX(-50%)", background:C.primary, color:"#fff", padding:"3px 12px", borderRadius:4, fontSize:11, fontWeight:800 }}>
                ⊹ ARRANGE — drag to move, double-click to rename
              </div>
            )}
            <div className="ccf-no-print" style={{ position:"absolute", bottom:12, right:12, display:"flex", gap:8, flexWrap:"wrap", justifyContent:"flex-end" }}>
              {[["Done", C.done], ["Active", C.active], ["Blocked", C.blocked], ["Todo", DK.border]].map(([l, col]) => (
                <div key={l} style={{ display:"flex", alignItems:"center", gap:4, fontSize:10, color:DK.sub }}>
                  <span style={{ width:7, height:7, borderRadius:"50%", background:col, display:"inline-block" }}/>
                  {l}
                </div>
              ))}
            </div>
          </div>

          {/* RIGHT PANEL */}
          <div className="ccf-no-print" style={{ width:316, background:DK.panel, borderLeft:`1px solid ${DK.border}`, display:"flex", flexDirection:"column", overflow:"hidden" }}>
            <div style={{ display:"flex", borderBottom:`1px solid ${DK.border}`, flexShrink:0 }}>
              {[["details","📋","Details"], ["ai","🤖","AI"], ["notes","📝","Notes"], ["progress","📊","Progress"]].map(([id, icon, label]) => (
                <button key={id} onClick={() => setTab(id)}
                  style={{ flex:1, padding:"9px 2px", border:"none", cursor:"pointer", fontSize:8, fontWeight:800, textTransform:"uppercase", letterSpacing:"0.5px",
                    background: tab === id ? DK.surf : DK.panel,
                    color: tab === id ? C.primary : DK.sub,
                    borderBottom: tab === id ? `2px solid ${C.primary}` : "2px solid transparent" }}>
                  {icon}<br/>{label}
                </button>
              ))}
            </div>
            <div style={{ flex:1, overflow:"hidden", position:"relative" }}>
              <div style={{ display: tab === "details" ? "block" : "none", height:"100%", overflowY:"auto", padding:14 }}>
                <DetailsPanel selectedNode={selectedNode} setNodeStatus={setNodeStatus} setCheckItem={setCheckItem} addLog={addLog} onBypass={id => setBypassModal({ nodeId:id })}/>
              </div>
              <div style={{ display: tab === "ai" ? "flex" : "none", flexDirection:"column", height:"100%", overflow:"hidden", padding:14 }}>
                <AIPanel selectedNode={selectedNode} conversation={aiConversation} setConversation={setAiConversation} addLog={addLog} applyAIChange={applyAIChange}/>
              </div>
              <div style={{ display: tab === "notes" ? "block" : "none", height:"100%", overflowY:"auto", padding:14 }}>
                <NotesPanel selectedNode={selectedNode} nodeNotes={nodeNotes} setNodeNotes={setNodeNotes} sessionLog={sessionLog} addLog={addLog}/>
              </div>
              <div style={{ display: tab === "progress" ? "block" : "none", height:"100%", overflowY:"auto", padding:14 }}>
                <ProgressPanel nodesMap={nodes} sessionStart={sessionStart}/>
              </div>
            </div>
          </div>
        </div>

        {/* BYPASS MODAL */}
        {bypassModal && (
          <div className="ccf-no-print" style={{ position:"fixed", inset:0, background:"rgba(0,0,0,0.75)", display:"flex", alignItems:"center", justifyContent:"center", zIndex:100 }}>
            <div style={{ background:DK.panel, border:`1px solid ${DK.border}`, borderRadius:8, padding:20, width:320 }}>
              <div style={{ fontSize:13, fontWeight:700, color:"#dde4f0", marginBottom:8 }}>Skip ↷: {nodes[bypassModal.nodeId]?.label?.replace("\n"," ")}</div>
              <div style={{ fontSize:11, color:DK.sub, marginBottom:8 }}>Reason (optional):</div>
              <input value={bypassReason} onChange={e => setBypassReason(e.target.value)}
                onKeyDown={e => { if (e.key === "Enter") confirmBypass(); }}
                placeholder="e.g. Already reviewed during phase 6B"
                autoFocus
                style={{ width:"100%", padding:"7px 8px", background:DK.surf, border:`1px solid ${DK.border}`, borderRadius:4, color:"#dde4f0", fontSize:12, boxSizing:"border-box", outline:"none", marginBottom:14 }}/>
              <div style={{ display:"flex", gap:8 }}>
                <button onClick={confirmBypass} style={{ flex:1, padding:"7px 0", background:"#0891b2", color:"#fff", border:"none", borderRadius:4, cursor:"pointer", fontSize:12, fontWeight:700 }}>Confirm Skip</button>
                <button onClick={() => { setBypassModal(null); setBypassReason(""); }} style={{ flex:1, padding:"7px 0", background:DK.surf, color:DK.sub, border:`1px solid ${DK.border}`, borderRadius:4, cursor:"pointer", fontSize:12 }}>Cancel</button>
              </div>
              <div style={{ fontSize:9, color:DK.sub, marginTop:8, textAlign:"center" }}>Press Esc to cancel</div>
            </div>
          </div>
        )}

        {/* DOWNSTREAM MODAL */}
        {downstreamModal && (
          <div className="ccf-no-print" style={{ position:"fixed", inset:0, background:"rgba(0,0,0,0.75)", display:"flex", alignItems:"center", justifyContent:"center", zIndex:100 }}>
            <div style={{ background:DK.panel, border:`1px solid ${DK.border}`, borderRadius:8, padding:20, width:340 }}>
              <div style={{ fontSize:13, fontWeight:700, color:"#dde4f0", marginBottom:6 }}>⚠ Downstream Steps Affected</div>
              <div style={{ fontSize:12, color:DK.sub, marginBottom:10 }}>Marking <strong style={{ color:"#dde4f0" }}>{downstreamModal.nodeLabel?.replace("\n"," ")}</strong> as <strong style={{ color:"#dde4f0" }}>{downstreamModal.newStatus}</strong> affects:</div>
              {downstreamModal.affected.map(nid => (
                <div key={nid} style={{ fontSize:11, color:C.accent, marginBottom:3 }}>• {nodes[nid]?.label?.replace("\n"," ")} ({nodes[nid]?.status})</div>
              ))}
              <div style={{ display:"flex", gap:8, marginTop:14 }}>
                <button onClick={() => { setNodeStatus(downstreamModal.nodeId, downstreamModal.newStatus, true); setDownstreamModal(null); }}
                  style={{ flex:1, padding:"7px 0", background:C.primary, color:"#fff", border:"none", borderRadius:4, cursor:"pointer", fontSize:12, fontWeight:700 }}>Proceed</button>
                <button onClick={() => setDownstreamModal(null)}
                  style={{ flex:1, padding:"7px 0", background:DK.surf, color:DK.sub, border:`1px solid ${DK.border}`, borderRadius:4, cursor:"pointer", fontSize:12 }}>Cancel</button>
              </div>
              <div style={{ fontSize:9, color:DK.sub, marginTop:8, textAlign:"center" }}>Press Esc to cancel</div>
            </div>
          </div>
        )}
      </div>
    </ErrorBoundary>
  );
}
