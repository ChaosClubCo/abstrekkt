import { useState } from 'react';
import { nanoid } from 'nanoid';

/**
 * The possible categories that can be searched. These correspond to
 * different modules in the FlashFusion platform (projects, templates,
 * documentation, support articles, etc.). Additional categories can
 * be added as needed.
 */
export type SearchCategory = 'projects' | 'templates' | 'documentation' | 'support';

export interface SearchResult {
  id: string;
  category: SearchCategory;
  title: string;
  snippet: string;
}

/**
 * Hook for performing a simple search across multiple categories.
 * Maintains a list of results, selected categories, and a log of
 * search queries. In production, this would call a backend search
 * service or index (e.g. Algolia, ElasticSearch) and return results
 * with ranking, highlighting, etc.
 */
export function useComprehensiveSearch() {
  const [query, setQuery] = useState('');
  const [categories, setCategories] = useState<SearchCategory[]>(['projects', 'templates', 'documentation', 'support']);
  const [results, setResults] = useState<SearchResult[]>([]);
  const [logs, setLogs] = useState<string[]>([]);

  // Example in-memory data sets for demonstration
  const data: Record<SearchCategory, { title: string; snippet: string }[]> = {
    projects: [
      { title: 'Weather App', snippet: 'A full stack weather application generated by AI.' },
      { title: 'E-commerce Store', snippet: 'An online shop with integrated payments.' },
    ],
    templates: [
      { title: 'Todo List Template', snippet: 'Simple todo list with CRUD operations.' },
      { title: 'Blog Template', snippet: 'Markdown blog with comments and tags.' },
    ],
    documentation: [
      { title: 'Getting Started', snippet: 'Learn how to set up your environment and create your first app.' },
      { title: 'API Reference', snippet: 'Detailed description of all available endpoints.' },
    ],
    support: [
      { title: 'How to reset your password', snippet: 'Steps to recover your account password.' },
      { title: 'Troubleshooting deployment', snippet: 'Common issues during deployment and how to fix them.' },
    ],
  };

  /**
   * Perform a search across selected categories. Updates results state.
   */
  const performSearch = () => {
    const trimmed = query.trim().toLowerCase();
    if (!trimmed) {
      setResults([]);
      return;
    }
    const newResults: SearchResult[] = [];
    categories.forEach((category) => {
      const items = data[category];
      items.forEach((item) => {
        if (item.title.toLowerCase().includes(trimmed) || item.snippet.toLowerCase().includes(trimmed)) {
          newResults.push({ id: nanoid(), category, title: item.title, snippet: item.snippet });
        }
      });
    });
    setResults(newResults);
    setLogs((prev) => [`[${new Date().toISOString()}] Searched "${query}" in ${categories.join(', ')}`, ...prev]);
  };

  const toggleCategory = (category: SearchCategory) => {
    setCategories((prev) =>
      prev.includes(category)
        ? prev.filter((c) => c !== category)
        : [...prev, category]
    );
  };

  return {
    query,
    setQuery,
    categories,
    toggleCategory,
    results,
    performSearch,
    logs,
  };
}